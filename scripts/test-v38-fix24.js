ok('index weather 38-24',idx.includes('jr-v38-weather-fields-sync.js?v=38-24'));
ok('index mobile 38-24',idx.includes('jr-v38-mobile-sync.js?v=38-24'));
ok('meta FIX24',idx.includes('jr-build-fix24'));
